--[[
    constants.lua

    Числовые константы для hot path (ADR-006).
    Никаких строк здесь не используется во время выполнения кадра — строковые
    имена типов узлов существуют только в публичном API (см. node/api.lua,
    будет добавлен в M7 вместе с виджетами) и в debug-выводе.

    Загрузочная модель: MTA грузит client-скрипты одного ресурса в общее
    Lua-окружение (общий _G), без гарантированного стандартного require()
    между файлами. Поэтому вместо require/return модули публикуют себя в
    общую таблицу DXUI (§46 ТЗ — предсказуемый порядок загрузки, без
    динамических loadstring/dependency-резолверов). Порядок публикации
    зафиксирован порядком <script> тегов в meta.xml.
]]

DXUI = DXUI or {}

local C = {}
DXUI.Constants = C

-- ---------------------------------------------------------------------
-- Dirty flags (битовая маска, ADR-001)
-- Каждый бит инвалидирует ровно одну подсистему конвейера.
-- ---------------------------------------------------------------------
C.DIRTY_NONE       = 0x000
C.DIRTY_LAYOUT     = 0x001  -- нужен пересчёт позиции/размера потомков
C.DIRTY_STYLE      = 0x002  -- нужен пересчёт визуального стиля
C.DIRTY_CONTENT    = 0x004  -- изменился текст/изображение/содержимое
C.DIRTY_TRANSFORM  = 0x008  -- изменилась позиция/масштаб/поворот
C.DIRTY_VISIBILITY = 0x010  -- изменилась видимость/culling-состояние
C.DIRTY_RENDER     = 0x020  -- нужно перегенерировать render command
C.DIRTY_CHILDREN   = 0x040  -- изменился состав детей (добавлен/удалён узел)
C.DIRTY_INPUT      = 0x080  -- нужно обновить hit-test/interactive список
C.DIRTY_QUEUED     = 0x100  -- служебный бит: узел уже в dirtyList за этот кадр (ADR-003)

C.DIRTY_ALL_PUBLIC = 0x0FF  -- маска всех "содержательных" битов без QUEUED

-- M9 (Optimization): слитый бит для "позиция/размер изменились".
-- setPosition/setSize/anim-pool пишут ОДИН бит вместо трёх (DIRTY_LAYOUT |
-- DIRTY_TRANSFORM | DIRTY_RENDER), т.к. все три подсистемы обязаны
-- переработать такой узел. Layout-проход проверяет бит DIRTY_LAYOUT (в
-- маске DIRTY_POS), Builder — DIRTY_RENDER (тоже в маске).
C.DIRTY_POS = C.DIRTY_LAYOUT + C.DIRTY_TRANSFORM + C.DIRTY_RENDER -- 0x091

-- ---------------------------------------------------------------------
-- Node flags
-- ---------------------------------------------------------------------
C.FLAG_VISIBLE = 0x01  -- участвует в рендере (не путать с culling — это ручной флаг)
C.FLAG_ENABLED = 0x02  -- участвует в hit-test/input
C.FLAG_STATIC  = 0x04  -- hint для RT-кэширования (ADR-004, auto-уровень)
C.FLAG_PINNED_RT = 0x08 -- явный pinned RT-кэш (ADR-004, не вытесняется автоматически)
C.FLAG_CLIP    = 0x10  -- обрезает детей по своим границам (scroll/panel clipping, M5)
C.FLAG_OPACITY = 0x40  -- узел имеет кастомную opacity (не 255), M5
C.FLAG_BLUR    = 0x80  -- узел имеет blur (не 0), M5

C.FLAG_DEFAULT = C.FLAG_VISIBLE + C.FLAG_ENABLED

-- M10: максимальная глубина вложенных clip-областей (полный RT-стек).
-- Глубже 4 вложенных clip-контейнеров — практически не встречается;
-- уровни сверх лимита сводятся к innermost (документированное ограничение).
C.MAX_CLIP_DEPTH = 4

-- ---------------------------------------------------------------------
-- Node types (числовые, публичные строковые имена мапятся в M7)
-- ---------------------------------------------------------------------
C.NODE_ROOT     = 0
C.NODE_PANEL    = 1
C.NODE_BUTTON   = 2
C.NODE_TEXT     = 3
C.NODE_IMAGE    = 4
C.NODE_WINDOW   = 5
C.NODE_CUSTOM   = 99 -- зарезервировано под кастомные рендереры (§53 исходного ТЗ)

-- Специальное значение "нет узла" — 0 не используется как валидный id/slot,
-- id начинаются с 1, поэтому 0 однозначно означает "отсутствует".
C.NIL_ID = 0

-- ---------------------------------------------------------------------
-- M4: Layout modes (ADR-007) и anchors (ADR-008).
-- Числовые, как и всё остальное в hot path (§49/ADR-006).
-- ---------------------------------------------------------------------
C.LAY_ABS    = 0  -- x/y — абсолютные экранные координаты (режим M1–M3)
C.LAY_REL    = 1  -- x/y — доля 0..1 от родительского контейнера (§40/§41 ТЗ)
C.LAY_CENTER = 2  -- узел центрируется в родителе, x/y игнорируются (§40 ТЗ)

-- Якорь точки привязки узла: какая точка узла "приклеивается" к (x,y).
C.ANCHOR_TL = 0   -- top-left    (значение по умолчанию)
C.ANCHOR_TC = 1   -- top-center
C.ANCHOR_TR = 2   -- top-right
C.ANCHOR_ML = 3   -- middle-left
C.ANCHOR_MC = 4   -- middle-center
C.ANCHOR_MR = 5   -- middle-right
C.ANCHOR_BL = 6   -- bottom-left
C.ANCHOR_BC = 7   -- bottom-center
C.ANCHOR_BR = 8   -- bottom-right

-- ---------------------------------------------------------------------
-- M2: Render command types (ADR §13 исходного ТЗ)
-- ---------------------------------------------------------------------
C.CMD_RECT  = 1
C.CMD_IMAGE = 2
C.CMD_TEXT  = 3

C.NO_CMD_SLOT = 0 -- узел ещё не получил render command (или не эмитит его)

-- ---------------------------------------------------------------------
-- M2: Layers (§59 исходного ТЗ) — числовые, задают порядок сортировки
-- ---------------------------------------------------------------------
C.LAYER_BASE    = 0
C.LAYER_OVERLAY = 1
C.LAYER_MODAL   = 2
C.LAYER_POPUP   = 3
C.LAYER_TOOLTIP = 4
C.LAYER_DEBUG   = 5

-- ---------------------------------------------------------------------
-- M3: Input event types (числовые, ADR-006). Строковые имена ("click",
-- "mousedown"...) существуют только в публичном API proxy:on(), маппинг —
-- в input/events.lua, один раз при регистрации слушателя (cold path).
-- ---------------------------------------------------------------------
-- M4: режим отладки библиотеки. Определяется здесь (а не в bootstrap),
-- т.к. это константа среды, а не состояние кадра. true — debug-лог в
-- onClientResourceStart (bootstrap.lua); в hot path не читается никогда,
-- поэтому стоимость в проде = 0 (§50 ТЗ — production: minimal overhead).
C.DEBUG = false

-- ---------------------------------------------------------------------
-- M3: Input event types (числовые, ADR-006). Строковые имена ("click",
-- "mousedown"...) существуют только в публичном API proxy:on(), маппинг —
-- в input/events.lua, один раз при регистрации слушателя (cold path).
-- ---------------------------------------------------------------------
C.EVENT_CLICK      = 1
C.EVENT_MOUSEDOWN  = 2
C.EVENT_MOUSEUP    = 3
C.EVENT_MOUSEENTER = 4
C.EVENT_MOUSELEAVE = 5

-- ---------------------------------------------------------------------
-- M6: Animation (ADR-010). НИКАКИХ per-node таймеров (setTimer запрещён
-- архитектурой): анимация = данные (from/to/dur/ease) в пуле + единый
-- тик-проход AnimationPool:update(now) в начале renderFrame.
-- ---------------------------------------------------------------------
C.NO_ANIM_SLOT = 0 -- "нет активной анимации" (аналог NO_CMD_SLOT)

C.ANIM_X = 1
C.ANIM_Y = 2
C.ANIM_W = 3
C.ANIM_H = 4

C.EASE_LINEAR  = 0
C.EASE_IN      = 1  -- cubic in:   t^3
C.EASE_OUT     = 2  -- cubic out:  1 - (1-t)^3
C.EASE_IN_OUT  = 3  -- smoothstep: t^2 * (3 - 2t)
C.EASE_DEFAULT = C.EASE_IN_OUT
